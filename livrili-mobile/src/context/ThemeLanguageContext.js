const ThemeLanguageContext = createContext();

export const ThemeLanguageProvider = ({ children }) => {
  const [lang, setLang] = useState('fr');
  const isRTL = lang === 'ar' || lang === 'dz';

  useEffect(() => {
    // Désactiver le RTL natif persistant pour éviter que le Français reste inversé
    I18nManager.allowRTL(false);
    I18nManager.forceRTL(false);

    SecureStore.getItemAsync('app_lang')
      .then((saved) => {
        if (saved && translations[saved]) {
          setLang(saved);
        }
      })
      .catch(() => {});
  }, []);

  const changeLanguage = async (newLang) => {
    setLang(newLang);
    try {
      await SecureStore.setItemAsync('app_lang', newLang);
    } catch (e) {}
  };

  const t = (key) => translations[lang]?.[key] || translations['fr'][key] || key;

  return (
    <ThemeLanguageContext.Provider value={{ lang, isRTL, changeLanguage, t, COLORS }}>
      {children}
    </ThemeLanguageContext.Provider>
  );
};

export const useThemeLang = () => useContext(ThemeLanguageContext);